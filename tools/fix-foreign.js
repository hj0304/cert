function repair(html) {
  let s = String(html);
  for (let pass = 0; pass < 5; pass++) {
    const before = s;
    for (const [from, to] of ENTRIES) {
      if (s.includes(from)) s = s.split(from).join(to);
    }
    if (s === before) break;
  }
  return s;
}

